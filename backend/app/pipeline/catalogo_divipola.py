PREFIJOS_INSTITUCIONALES = ("CAT ", "CREAD ", "SEDE ", "CENTRO ")


def normalizar_texto_geografico(texto: str) -> str:
    """Convierte a mayúsculas sin tildes y limpia prefijos institucionales ('CAT ', 'CREAD ')."""
    limpio = "".join(
        c for c in unicodedata.normalize("NFD", str(texto or "")) if unicodedata.category(c) != "Mn"
    ).upper()
    limpio = " ".join(limpio.replace("-", " ").replace("_", " ").split())
    cambio = True
    while cambio:
        cambio = False
        for prefijo in PREFIJOS_INSTITUCIONALES:
            if limpio.startswith(prefijo):
                limpio = limpio[len(prefijo) :].strip()
                cambio = True
    return limpio


def _construir_indice_nombres_municipios() -> dict[str, str]:
    """Construye índice de nombre normalizado de municipio -> mpio_code (priorizando Tolima '73')."""
    indice: dict[str, str] = {}
    for m_code, (d_code, m_name, _lat, _lon) in MUNICIPIOS_DIVIPOLA.items():
        clave = normalizar_texto_geografico(m_name)
        if not clave:
            continue
        if clave not in indice or d_code == "73":
            indice[clave] = m_code
    return indice


_INDICE_NOMBRES_MPIO = _construir_indice_nombres_municipios()


def _buscar_por_tokens(cand_nombre: str) -> str | None:
    tokens_ordenados = sorted(cand_nombre.split(), key=len, reverse=True)
    for token in tokens_ordenados:
        if len(token) >= 3:
            hallado = ALIAS_CAT_A_MPIO.get(token) or _INDICE_NOMBRES_MPIO.get(token)
            if hallado:
                return hallado
    return None


def _resolver_codigo_mpio(cand_nombre: str, cand_corto: str) -> str | None:
    directo = (
        ALIAS_CAT_A_MPIO.get(cand_nombre)
        or _INDICE_NOMBRES_MPIO.get(cand_nombre)
        or ALIAS_CAT_A_MPIO.get(cand_corto)
        or _INDICE_NOMBRES_MPIO.get(cand_corto)
    )
    if directo:
        return directo
    return _buscar_por_tokens(cand_nombre) if cand_nombre else None


def resolver_ubicacion_cat(cat_name: str, cat_shortname: str = "") -> UbicacionCat | None:
    """Resuelve un CAT de Moodle a su municipio y departamento oficial del DANE (DIVIPOLA).

    Orden de resolución:
      1. Alias exacto por ``cat_name`` normalizado o ``cat_shortname`` normalizado.
      2. Coincidencia exacta contra los 1.122 nombres municipales del DANE.
      3. Coincidencia por inclusión de palabra/token (p. ej. 'BOGOTA TUNAL' -> 'BOGOTA').
    """
    cand_nombre = normalizar_texto_geografico(cat_name)
    cand_corto = normalizar_texto_geografico(cat_shortname)
    mpio_code = _resolver_codigo_mpio(cand_nombre, cand_corto)

    if not mpio_code or mpio_code not in MUNICIPIOS_DIVIPOLA:
        return None

    dpto_code, mpio_name, lat, lon = MUNICIPIOS_DIVIPOLA[mpio_code]
    dpto_name = DEPARTAMENTOS_DIVIPOLA.get(dpto_code, dpto_code)
    return {
        "dpto_code": dpto_code,
        "dpto_name": dpto_name,
        "mpio_code": mpio_code,
        "mpio_name": mpio_name,
        "lat": lat,
        "lon": lon,
    }
